#!/usr/bin/env bash
# platform-compat.sh — Cross-platform compatibility layer.
#
# Source this file as the FIRST action in install.sh (and in any standalone
# script that uses sed_i or get_local_ips) before any bash-4+ syntax or
# platform-specific commands are used.

# ---------------------------------------------------------------------------
# 1. Bash version guard — macOS ships bash 3.2 which lacks declare -g,
#    ${var,,}, etc.  Re-exec with Homebrew bash 4+ when available.
# ---------------------------------------------------------------------------
if [ "${BASH_VERSINFO[0]}" -lt 4 ]; then
  for _bp in /opt/homebrew/bin/bash /usr/local/bin/bash; do
    if [ -x "$_bp" ] && [ "$("$_bp" -c 'echo ${BASH_VERSINFO[0]}' 2>/dev/null)" -ge 4 ] 2>/dev/null; then
      exec "$_bp" "$0" "$@"
    fi
  done
  echo "ERROR: Bash 4.0+ is required." >&2
  echo "       On macOS, install it via: brew install bash" >&2
  exit 1
fi

# ---------------------------------------------------------------------------
# 2. Detect platform (exported so child scripts can read it)
# ---------------------------------------------------------------------------
PLATFORM=$(uname -s)
export PLATFORM

# ---------------------------------------------------------------------------
# 3. Supplement PATH on macOS so Homebrew tools (envsubst, etc.) are found
# ---------------------------------------------------------------------------
if [[ "$PLATFORM" == "Darwin" ]]; then
  export PATH="/usr/local/bin:/opt/homebrew/bin:$PATH"
fi

# ---------------------------------------------------------------------------
# 4. sed_i — cross-platform in-place sed
#
#    BSD sed (macOS): sed -i '' 's/foo/bar/' file   (empty-string required)
#    GNU sed (Linux): sed -i 's/foo/bar/' file       (no empty-string)
#
# Usage: sed_i 's/pattern/replace/' file
# ---------------------------------------------------------------------------
sed_i() {
  if [[ "$PLATFORM" == "Darwin" ]]; then
    sed -i '' "$@"
  else
    sed -i "$@"
  fi
}
export -f sed_i

# ---------------------------------------------------------------------------
# 5. get_local_ips — cross-platform non-loopback IPv4 listing
#
#    macOS has no `hostname -I`; use ifconfig instead.
#    Outputs one IP per line (up to three addresses).
# ---------------------------------------------------------------------------
get_local_ips() {
  if [[ "$PLATFORM" == "Darwin" ]]; then
    ifconfig | awk '/inet / && $2 != "127.0.0.1" {print $2}' | head -3
  else
    hostname -I | awk '{for(i=1;i<=NF && i<=3;i++) print $i}'
  fi
}
export -f get_local_ips

# ---------------------------------------------------------------------------
# 6. is_macos — portable platform predicate, exported for child scripts
# ---------------------------------------------------------------------------
is_macos() {
  [[ "${PLATFORM:-$(uname -s)}" == "Darwin" ]]
}
export -f is_macos

# ---------------------------------------------------------------------------
# 7. DOCKER_CERTS_PATH — Docker TLS certificate directory
#
#    Linux: /etc/docker/certs   (generated by gen-certs.sh)
#    macOS Docker Desktop: this path does not exist; use ~/.docker/certs
#    so the docker-compose volume mount never fails.
# ---------------------------------------------------------------------------
if [[ -z "${DOCKER_CERTS_PATH:-}" ]]; then
  if [[ "$PLATFORM" == "Darwin" ]]; then
    DOCKER_CERTS_PATH="$HOME/.docker/certs"
    mkdir -p "$DOCKER_CERTS_PATH"
  else
    DOCKER_CERTS_PATH="/etc/docker/certs"
  fi
fi
export DOCKER_CERTS_PATH
