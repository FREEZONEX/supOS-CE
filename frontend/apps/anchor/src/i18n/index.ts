// 宿主 context 下发的语言优先于 localStorage（ThemeBridge 维护）；
// 扫码分享页等无宿主场景保持 null，走 localStorage/浏览器语言
let localeOverride: Locale | null = null;

export function setLocaleOverride(language: string | null) {
  if (!language) {
    localeOverride = null;
    return;
  }
  const normalized = language.trim().replace('_', '-').toLowerCase();
  localeOverride = normalized.startsWith('zh') ? 'zh-CN' : 'en-US';
}

export function getLocale(): Locale {
  if (localeOverride) return localeOverride;
  let stored = '';
  try {
    stored = window.localStorage.getItem(APP_LANG_KEY) || '';
  } catch {
    // iframe 沙箱等场景下禁止访问 storage 时退回浏览器语言
  }
  const normalized = (stored || window.navigator.language).trim().replace('_', '-').toLowerCase();
  return normalized.startsWith('zh') ? 'zh-CN' : 'en-US';
}

export const APP_LANG_STORAGE_KEY = APP_LANG_KEY;

export function t(key: string, params?: Record<string, string | number>): string {
  const raw = MESSAGES[getLocale()][key] ?? MESSAGES['en-US'][key] ?? key;
  if (!params) return raw;
  return raw.replace(/\{(\w+)\}/g, (_, name: string) =>
    params[name] !== undefined ? String(params[name]) : `{${name}}`
  );
}
